package com.wealth.bss.query;

public final class QueryConstants {

	private QueryConstants() {
	}

	private static final String WEALTH_USERS = "WEALTH_USERS";
	private static final String WEALTH_ROLE_MENUS = "WEALTH_ROLE_MENUS";
	private static final String WEALTH_SNAPSHOTS = "WEALTH_SNAPSHOTS";
	private static final String WEALTH_ACCOUNTS = "WEALTH_ACCOUNTS";
	private static final String WEALTH_ACCOUNT_SUBTYPES = "WEALTH_ACCOUNT_SUBTYPES";
	private static final String WEALTH_ACCOUNT_BALANCES = "WEALTH_ACCOUNT_BALANCES";
	private static final String WEALTH_V_LATEST_BALANCES = "WEALTH_V_LATEST_BALANCES";
	private static final String WEALTH_ACCOUNT_SPLITS = "WEALTH_ACCOUNT_SPLITS";
	private static final String WEALTH_ACCOUNT_SPLIT_BALANCES = "WEALTH_ACCOUNT_SPLIT_BALANCES";
	private static final String WEALTH_ACCOUNT_SPLIT_MOVES = "WEALTH_ACCOUNT_SPLIT_MOVES";

	// password_hash is never selected here
	public static final String FIND_WEALTH_USER_BY_ID = "SELECT ID, EMAIL, ROLE, SESSION_VERSION, CREATED_AT AS CRTD_DT FROM " + WEALTH_USERS + " WHERE ID = CAST(? AS UUID)";

	public static final String FIND_CREDENTIAL_BY_EMAIL = "SELECT ID, EMAIL, PASSWORD_HASH, ROLE, SESSION_VERSION FROM " + WEALTH_USERS + " WHERE EMAIL = ?";

	public static final String INSERT_WEALTH_USER = "INSERT INTO " + WEALTH_USERS + " (EMAIL, PASSWORD_HASH) VALUES (?, ?) ON CONFLICT (EMAIL) DO NOTHING RETURNING ID, EMAIL, ROLE, SESSION_VERSION, CREATED_AT AS CRTD_DT";

	// a new hash bumps SESSION_VERSION, which signs out every older token
	public static final String UPDATE_WEALTH_USER_PASSWORD = "UPDATE " + WEALTH_USERS + " SET PASSWORD_HASH = ?, SESSION_VERSION = SESSION_VERSION + 1 WHERE EMAIL = ? RETURNING ID, EMAIL, ROLE, SESSION_VERSION, CREATED_AT AS CRTD_DT";

	public static final String FIND_MENUS_BY_ROLE = "SELECT ARRAY_TO_STRING(MENUS, ',') FROM " + WEALTH_ROLE_MENUS + " WHERE ROLE = ?";

	// The audit triggers (migrations 0008, 0012, 0054) read wealth.actor and wealth.user_id; true = for this transaction only. Run it first in every write.
	public static final String SET_ACTOR = "SELECT SET_CONFIG('wealth.actor', ?, TRUE) || SET_CONFIG('wealth.user_id', ?, TRUE)";

	// ---- admin: roles and menus ----
	public static final String COUNT_USERS_BY_ROLE = "SELECT COUNT(*) FROM " + WEALTH_USERS + " WHERE ROLE = ?";

	public static final String UPSERT_ROLE_MENUS = "INSERT INTO " + WEALTH_ROLE_MENUS + " (ROLE, MENUS, UPDATED_BY) VALUES (?, STRING_TO_ARRAY(?, ','), CAST(? AS UUID)) "
			+ "ON CONFLICT (ROLE) DO UPDATE SET MENUS = EXCLUDED.MENUS, UPDATED_AT = NOW(), UPDATED_BY = EXCLUDED.UPDATED_BY "
			+ "RETURNING ROLE, ARRAY_TO_STRING(MENUS, ',') AS MENUS, UPDATED_AT AS UPDT_DT, UPDATED_BY";

	// ---- admin: saved records; the optional text (already wrapped as %text%) matches the name or the key ----
	public static final String FIND_SNAPSHOTS_BY_USER = "SELECT ID, USER_ID, SOURCE_KEY, SOURCE_NAME, SNAPSHOT_DATE, PAYLOAD::TEXT AS PAYLOAD, CREATED_AT AS CRTD_DT FROM " + WEALTH_SNAPSHOTS
			+ " WHERE USER_ID = CAST(? AS UUID) AND (CAST(? AS TEXT) IS NULL OR SOURCE_NAME ILIKE CAST(? AS TEXT) OR SOURCE_KEY ILIKE CAST(? AS TEXT)) ORDER BY SNAPSHOT_DATE DESC, CREATED_AT DESC";

	// ---- accounts ----
	// account_type, current_balance, balance_as_of and balance_status are legacy copies and are never selected (docs/migration/db-review.md section 5).
	private static final String ACCOUNT_COLUMNS = "ID, USER_ID, ACCOUNT_KEY, BANK_NAME, ACCOUNT_NAME, SUBTYPE_CODE, MASKED_IDENTIFIER, TRIM(CURRENCY) AS CURRENCY, STATUS, "
			+ "FD_PRINCIPAL, FD_BOOKED_ON, FD_MATURITY_ON, FD_PAYOUT, FD_COMPOUNDING, CREATED_AT AS CRTD_DT, UPDATED_AT AS UPDT_DT";

	public static final String FIND_ACCOUNTS_BY_USER = "SELECT " + ACCOUNT_COLUMNS + " FROM " + WEALTH_ACCOUNTS + " WHERE USER_ID = CAST(? AS UUID) ORDER BY BANK_NAME, ACCOUNT_NAME";

	public static final String FIND_ACCOUNT_BY_ID = "SELECT " + ACCOUNT_COLUMNS + " FROM " + WEALTH_ACCOUNTS + " WHERE USER_ID = CAST(? AS UUID) AND ID = CAST(? AS UUID)";

	public static final String FIND_ACCOUNT_SUBTYPES = "SELECT CODE, CATEGORY, LABEL, VALUATION, SORT_ORDER FROM " + WEALTH_ACCOUNT_SUBTYPES + " ORDER BY CATEGORY, SORT_ORDER";

	// the old type column carries the subtype too, so it is written with the same value
	public static final String INSERT_ACCOUNT = "INSERT INTO " + WEALTH_ACCOUNTS + " (USER_ID, ACCOUNT_KEY, BANK_NAME, ACCOUNT_NAME, ACCOUNT_TYPE, SUBTYPE_CODE, MASKED_IDENTIFIER, CURRENCY, "
			+ "BALANCE_STATUS, FD_PRINCIPAL, FD_BOOKED_ON, FD_MATURITY_ON, FD_PAYOUT, FD_COMPOUNDING) "
			+ "VALUES (CAST(? AS UUID), ?, ?, ?, ?, ?, ?, ?, 'unknown', ?, ?, ?, ?, ?) ON CONFLICT (USER_ID, ACCOUNT_KEY) DO NOTHING RETURNING " + ACCOUNT_COLUMNS;

	public static final String UPDATE_ACCOUNT_FD_TERMS = "UPDATE " + WEALTH_ACCOUNTS + " SET FD_PRINCIPAL = COALESCE(?, FD_PRINCIPAL), FD_BOOKED_ON = COALESCE(?, FD_BOOKED_ON), "
			+ "FD_MATURITY_ON = COALESCE(?, FD_MATURITY_ON), FD_PAYOUT = COALESCE(?, FD_PAYOUT), FD_COMPOUNDING = COALESCE(?, FD_COMPOUNDING), UPDATED_AT = NOW() "
			+ "WHERE USER_ID = CAST(? AS UUID) AND ID = CAST(? AS UUID) RETURNING " + ACCOUNT_COLUMNS;

	// ---- account balances ----
	public static final String FIND_LATEST_BALANCES_BY_USER = "SELECT B.ACCOUNT_ID, B.AS_OF, B.BALANCE, B.STATUS, B.NOTE FROM " + WEALTH_V_LATEST_BALANCES + " B JOIN " + WEALTH_ACCOUNTS
			+ " A ON A.ID = B.ACCOUNT_ID WHERE A.USER_ID = CAST(? AS UUID)";

	public static final String FIND_BALANCE_HISTORY = "SELECT B.ACCOUNT_ID, B.AS_OF, B.BALANCE, B.STATUS, B.NOTE, B.ENTERED_BY, B.CONFIRMED_AT, B.REJECTED_AT, B.REJECTED_REASON FROM "
			+ WEALTH_ACCOUNT_BALANCES + " B JOIN " + WEALTH_ACCOUNTS + " A ON A.ID = B.ACCOUNT_ID WHERE A.USER_ID = CAST(? AS UUID) AND B.ACCOUNT_ID = CAST(? AS UUID) "
			+ "AND B.REJECTED_AT IS NULL ORDER BY B.AS_OF DESC LIMIT ?";

	// inserted only when the account belongs to the user; a balance already stored at the same moment is left alone
	public static final String INSERT_ACCOUNT_BALANCE = "INSERT INTO " + WEALTH_ACCOUNT_BALANCES + " (ACCOUNT_ID, AS_OF, BALANCE, STATUS, NOTE, ENTERED_BY) "
			+ "SELECT A.ID, ?, ?, ?, ?, ? FROM " + WEALTH_ACCOUNTS + " A WHERE A.USER_ID = CAST(? AS UUID) AND A.ID = CAST(? AS UUID) "
			+ "ON CONFLICT (ACCOUNT_ID, AS_OF) DO NOTHING RETURNING ACCOUNT_ID, AS_OF, BALANCE, STATUS, NOTE, ENTERED_BY";

	// the legacy copy on the account, moved only forward in time; kept while the old app runs on the same database
	public static final String UPDATE_ACCOUNT_BALANCE_COPY = "UPDATE " + WEALTH_ACCOUNTS + " SET CURRENT_BALANCE = ?, BALANCE_AS_OF = ?, BALANCE_STATUS = ?, UPDATED_AT = NOW() "
			+ "WHERE USER_ID = CAST(? AS UUID) AND ID = CAST(? AS UUID) AND (BALANCE_AS_OF IS NULL OR BALANCE_AS_OF < ?) RETURNING ID";

	// ---- account splits (read only for now) ----
	public static final String FIND_SPLITS_BY_ACCOUNT = "SELECT ID, USER_ID, ACCOUNT_ID, SPLIT_KEY, NAME, KIND, GOAL_AMOUNT, PURPOSE, SORT_ORDER, STATUS, CREATED_AT AS CRTD_DT, UPDATED_AT AS UPDT_DT FROM "
			+ WEALTH_ACCOUNT_SPLITS + " WHERE USER_ID = CAST(? AS UUID) AND ACCOUNT_ID = CAST(? AS UUID) AND STATUS = 'active' ORDER BY SORT_ORDER, NAME";

	public static final String FIND_LATEST_SPLIT_BALANCES_BY_ACCOUNT = "SELECT DISTINCT ON (B.SPLIT_ID) B.ID, B.SPLIT_ID, B.AS_OF, B.BALANCE, B.STATUS, B.NOTE, B.CREATED_AT AS CRTD_DT FROM "
			+ WEALTH_ACCOUNT_SPLIT_BALANCES + " B JOIN " + WEALTH_ACCOUNT_SPLITS + " S ON S.ID = B.SPLIT_ID WHERE S.USER_ID = CAST(? AS UUID) AND S.ACCOUNT_ID = CAST(? AS UUID) "
			+ "AND S.STATUS = 'active' ORDER BY B.SPLIT_ID, B.AS_OF DESC";

	public static final String FIND_SPLIT_MOVES_BY_ACCOUNT = "SELECT M.ID, M.SPLIT_ID, M.OCCURRED_AT, M.AMOUNT, M.TRANSACTION_ID, M.NOTE, M.CREATED_AT AS CRTD_DT FROM " + WEALTH_ACCOUNT_SPLIT_MOVES
			+ " M JOIN " + WEALTH_ACCOUNT_SPLITS + " S ON S.ID = M.SPLIT_ID WHERE S.USER_ID = CAST(? AS UUID) AND S.ACCOUNT_ID = CAST(? AS UUID) AND S.STATUS = 'active' "
			+ "ORDER BY M.OCCURRED_AT DESC";
}
