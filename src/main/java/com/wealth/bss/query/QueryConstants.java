	// The caller's active holdings with account, instrument and latest price (a missing price stays null); largest value first, then by symbol.
	public static final String FIND_HOLDING_DETAILS_BY_USER = "SELECT H.ACCOUNT_ID, A.BANK_NAME, A.ACCOUNT_NAME, TRIM(A.CURRENCY) AS ACCOUNT_CURRENCY, I.ID AS INSTRUMENT_ID, "
			+ "I.SYMBOL, I.NAME, I.ASSET_CLASS, I.UNIT, TRIM(I.CURRENCY) AS CURRENCY, I.PRICE_SOURCE_SYMBOL, I.ISIN, I.EXCHANGE, H.QUANTITY, H.INVESTED_VALUE, H.AS_OF AS HOLDING_AS_OF, "
			+ "H.STATUS, H.PRODUCT, H.T1_QUANTITY, H.COLLATERAL_QUANTITY, H.HAIRCUT, H.BROKER_CLOSE, H.BROKER_PNL, H.BROKER_PNL_PERCENT, "
			+ "P.PRICE, P.AS_OF AS PRICE_AS_OF, P.SOURCE AS PRICE_SOURCE, P.FX_TO_INR FROM WEALTH_HOLDINGS H JOIN WEALTH_ACCOUNTS A ON A.ID = H.ACCOUNT_ID "
			+ "JOIN WEALTH_INSTRUMENTS I ON I.ID = H.INSTRUMENT_ID LEFT JOIN WEALTH_V_LATEST_PRICES P ON P.INSTRUMENT_ID = I.ID "
			+ "WHERE A.USER_ID = CAST(? AS UUID) AND H.STATUS = 'active' ORDER BY H.QUANTITY * P.PRICE DESC NULLS LAST, I.SYMBOL";

	// Market value in rupees of each account's active holdings (quantity x latest price); a share without a price is left out. as_of is the newest price used.
	public static final String FIND_HOLDING_VALUES_BY_USER = "SELECT X.ACCOUNT_ID, MAX(P.AS_OF) AS AS_OF, "
			+ "SUM(X.QUANTITY * P.PRICE * CASE WHEN I.CURRENCY = 'INR' THEN 1 ELSE P.FX_TO_INR END) AS BALANCE FROM WEALTH_HOLDINGS X "
			+ "JOIN WEALTH_ACCOUNTS A ON A.ID = X.ACCOUNT_ID JOIN WEALTH_INSTRUMENTS I ON I.ID = X.INSTRUMENT_ID "
			+ "JOIN WEALTH_V_LATEST_PRICES P ON P.INSTRUMENT_ID = X.INSTRUMENT_ID WHERE A.USER_ID = CAST(? AS UUID) AND X.STATUS = 'active' GROUP BY X.ACCOUNT_ID";

	// the second parameter is the comma-separated ids of the instruments still held
	public static final String CLOSE_MISSING_HOLDINGS = "UPDATE WEALTH_HOLDINGS SET STATUS = 'closed', QUANTITY = 0, CLOSED_AT = COALESCE(CLOSED_AT, NOW()) "
			+ "WHERE ACCOUNT_ID = CAST(? AS UUID) AND STATUS = 'active' AND NOT (INSTRUMENT_ID = ANY (CAST(STRING_TO_ARRAY(?, ',') AS UUID[])))";
